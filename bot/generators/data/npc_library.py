# Quick lookups

ALL_NPCS: list[dict] = LEGENDARY + MEGA + NOTABLE + STANDARD

_BY_NAME: dict[str, dict] = {n["name"].lower(): n for n in ALL_NPCS}

TIER_ORDER = {"legendary": 0, "mega": 1, "notable": 2, "standard": 3}


def find_by_name(name: str) -> dict | None:
    return _BY_NAME.get(name.lower())


def by_tier(tier: str) -> list[dict]:
    return [n for n in ALL_NPCS if n["tier"] == tier]


def by_region(region: str) -> list[dict]:
    return [n for n in ALL_NPCS if region.lower() in n["region"].lower()]
